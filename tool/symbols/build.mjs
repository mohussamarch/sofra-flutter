// Writes lib/ui/symbols.g.dart from tool/symbols/map.json.
// Run: node tool/symbols/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const m = JSON.parse(readFileSync(new URL('./map.json', import.meta.url)));
const slug = (n) => n.toLowerCase().replace(/ /g, '_');
const q = (s) => `'${s.replace(/'/g, "\'")}'`;
const map = (o) => Object.entries(o).map(([k, v]) => `  ${q(k)}: ${q(slug(v))},`).join('\n');
writeFileSync(new URL('../../lib/ui/symbols.g.dart', import.meta.url), `// Generated by tool/symbols/build.mjs from tool/symbols/map.json; do not edit.
// Pictures: ${m.source}.

const symbolById = <String, String>{
${map(m.byId)}
};

const symbolByCategory = <String, String>{
${map(m.byCategory)}
};
`);

import {createHash} from 'node:crypto';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {TextDecoder} from 'node:util';

const root=fileURLToPath(new URL('../../',import.meta.url));
export const manifestFile='data/recipes/curated-local/flutter-manifest.json';
export const pinsFile='lib/data/recipe_library_assets.dart';
const files=[
 ['curated-local','data/recipes/curated-local/first-reviewed-20261014/normalized-recipes.json'],
 ['creator-website','data/recipes/arabic-youtube/2026-10-first-batch.json'],
 ['creator-website','data/recipes/arabic-youtube/second-batch-20261014/recipes.json'],
 ['creator-website','data/recipes/arabic-youtube/third-batch-20261014/recipes.json'],
 ['curated-local','data/recipes/curated-local/gap-review-20261014/normalized-recipes.json'],
 ['creator-website','data/recipes/arabic-youtube/fourth-batch-20261014/recipes.json'],
 ['curated-local','data/recipes/curated-local/third-reviewed-20261014/normalized-recipes.json'],
 ['curated-local','data/recipes/curated-local/fourth-reviewed-20261014/normalized-recipes.json'],
 ['creator-website','data/recipes/arabic-youtube/fifth-batch-20261014/recipes.json'],
 ['curated-local','data/recipes/curated-local/fifth-reviewed-20261014/normalized-recipes.json'],
 ['creator-website','data/recipes/arabic-youtube/sixth-batch-20261014/recipes.json'],
 ['creator-youtube','data/recipes/arabic-youtube/seventh-batch-20261015/recipes.json'],
 ['curated-local','data/recipes/curated-local/sixth-reviewed-20261015/normalized-recipes.json'],
 ['curated-local','data/recipes/curated-local/seventh-reviewed-20261015/normalized-recipes.json'],
];
const sha=v=>createHash('sha256').update(v).digest('hex');
const need=(v,m)=>{if(!v)throw Error(m);};
export function validateCreatorSource(row,kind){
 need(row&&row.sourceKind===kind&&['creator-website','creator-youtube'].includes(kind),'Creator source kind mismatch');
 need(row.runtimeReady!==true&&row.nutrition==null,'Research cannot enable runtime/nutrition');
 if(kind==='creator-website')need(row.youtubeDerived===false,'Creator source kind mismatch');
 else{
  const id=row.sourceVideoId;
  need(row.youtubeDerived===true&&typeof id==='string'&&/^[A-Za-z0-9_-]{11}$/.test(id)&&row.sourceUrl===`https://www.youtube.com/watch?v=${id}`,'YouTube source identity mismatch');
 }
}
export function safePath(file){
 need(typeof file==='string'&&/^(data\/recipes\/(curated-local|arabic-youtube)\/)([a-zA-Z0-9_-]+\/)*[a-zA-Z0-9_.-]+\.json$/.test(file)&&!file.includes('..'),'Unsafe recipe library path');
 return file;
}
function parseObject(raw){
 const value=JSON.parse(new TextDecoder('utf-8',{fatal:true,ignoreBOM:true}).decode(raw));
 need(value!==null&&typeof value==='object'&&!Array.isArray(value),'Expected JSON object');
 return value;
}
export async function buildManifest(read){
 const packs=[],ids=new Set();
 for(const [kind,file] of files){
  const raw=await read(file),data=parseObject(raw);
  need(Array.isArray(data.recipes)&&data.recipes.length>0,'Missing recipe rows');
  const snapshots=new Map();
  for(const row of data.recipes){
   const id=kind==='curated-local'?row.id:row.recipeId;
   need(typeof id==='string'&&id.trim().length>0&&!ids.has(id),'Duplicate recipe identity');ids.add(id);
   need(row.nutrition==null&&row.runtimeReady!==true,'Research cannot enable runtime/nutrition');
   if(kind==='curated-local'){
    const p=row.provenance,path=safePath(p.sourceSnapshotFile);
    const source=await read(path),hash=sha(source);
    need(hash===p.sourceSnapshotSha256,'Source snapshot drift: '+path);
    parseObject(source);
    snapshots.set(path,{file:path,sha256:hash});
   }else validateCreatorSource(row,kind);
  }
  packs.push({kind,file,sha256:sha(raw),sourceSnapshots:[...snapshots.values()].sort((a,b)=>a.file.localeCompare(b.file))});
 }
 return {schemaVersion:1,runtimeReady:false,packs};
}
export function dartPins(hash){return `// Generated by tool/recipes/build-recipe-library.mjs; do not edit.\nimport 'recipe_library_repository.dart';\n\nconst recipeLibraryManifestSha256 = '${hash}';\n\nRecipeLibraryRepository bundledRecipeLibrary() => RecipeLibraryRepository(\n  expectedManifestSha256: recipeLibraryManifestSha256,\n);\n`;}
export function outputMatches(file,actual,expected){
 return (file===pinsFile?actual.replace(/\r\n/g,'\n'):actual)===expected;
}
export async function run({check=false,base=root}={}){
 const read=file=>readFile(resolve(base,safePath(file)));
 const manifest=await buildManifest(read),text=JSON.stringify(manifest,null,2)+'\n';
 const outputs=[[manifestFile,text],[pinsFile,dartPins(sha(text))]];
 for(const [file,text] of outputs){
  const path=resolve(base,file);
  if(check)need(outputMatches(file,await readFile(path,'utf8'),text),'Stale library output: '+file);
  else{await mkdir(dirname(path),{recursive:true});await writeFile(path,text,'utf8');}
 }
 return {packs:manifest.packs.length,snapshots:manifest.packs.reduce((n,p)=>n+p.sourceSnapshots.length,0),manifestSha256:sha(text)};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 console.log(JSON.stringify(await run({check:process.argv.includes('--check')})));
}

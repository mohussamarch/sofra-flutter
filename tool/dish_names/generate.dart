// Builds lib/l10n/dish_names.g.dart from the reviewed dish-name glossary.
//
//   dart run tool/dish_names/generate.dart [glossary.json]
//
// The glossary defaults to data/dish-names/glossary.json (a copy of the
// reviewed deliverable). Each entry gives a catalog recipe id its English
// name, its pronunciation (only for transliterated names) and, when the
// same English name belongs to dishes of several countries, the country
// word shown as a tag next to the name.
//
// The entry's `displayEn` ("Egyptian Sayadieh") is deliberately not used:
// resolvedCollisions decides "country tag", so the country is shown as the
// tag beside the plain name, and writing it in the name too would say it
// twice.
//
// Old and rejected spellings (`enCurrent` without its brackets, and
// spellingDecisions[].rejected) become hidden search words, so a reader who
// types "Koshari" or "Stuffed Grape Leaves" still finds the dish.
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final source = args.isEmpty ? 'data/dish-names/glossary.json' : args.first;
  final json =
      jsonDecode(File(source).readAsStringSync()) as Map<String, dynamic>;
  final entries = (json['entries'] as List).cast<Map<String, dynamic>>();

  final uses = <String, int>{};
  for (final e in entries) {
    final en = _text(e['en'], 'en of ${e['id']}');
    uses[en] = (uses[en] ?? 0) + 1;
  }

  final rejected = <String, List<String>>{
    for (final d in (json['spellingDecisions'] as List? ?? const []))
      d['id'] as String: [for (final r in d['rejected'] as List) '$r'],
  };

  final ids = <String>{};
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/dish_names/generate.dart from')
    ..writeln('// data/dish-names/glossary.json. Do not edit by hand.')
    ..writeln()
    ..writeln("import 'dish_name.dart';")
    ..writeln()
    ..writeln('/// English names of catalog dishes, by recipe id.')
    ..writeln('const dishNames = <String, DishName>{');
  for (final e in entries) {
    final id = _text(e['id'], 'id');
    if (!ids.add(id)) throw FormatException('Duplicate glossary id $id');
    final en = _text(e['en'], 'en of $id');
    final say = e['pronunciation'];
    final parts = [_dart(en)];
    if (say != null) parts.add('say: ${_dart(_text(say, 'say of $id'))}');
    final also = <String>{};
    for (final old in [e['enCurrent'], ...?rejected[id]]) {
      if (old is! String) continue;
      final words = old.replaceAll(RegExp(r'[()]'), ' ').trim();
      final plain = words.replaceAll(RegExp(r'\s+'), ' ');
      if (plain.isNotEmpty && plain.toLowerCase() != en.toLowerCase()) {
        also.add(plain);
      }
    }
    if (also.isNotEmpty) {
      parts.add('also: [${also.map(_dart).join(', ')}]');
    }
    if (uses[en]! > 1) {
      final country = e['country'];
      if (country is! Map) {
        throw FormatException('$id shares "$en" but has no country');
      }
      parts
        ..add('countryEn: ${_dart(_text(country['en'], 'country of $id'))}')
        ..add('countryAr: ${_dart(_text(country['ar'], 'country of $id'))}');
    }
    out.writeln('  ${_dart(id)}: DishName(${parts.join(', ')}),');
  }
  out.writeln('};');

  const target = 'lib/l10n/dish_names.g.dart';
  File(target).writeAsStringSync(out.toString());
  Process.runSync('dart', ['format', target], runInShell: true);
  stdout.writeln('dish_names.g.dart: ${entries.length} names');
}

String _text(Object? v, String what) {
  if (v is! String || v.trim().isEmpty) {
    throw FormatException('Missing $what');
  }
  return v.trim();
}

/// A single-quoted Dart string literal.
String _dart(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";
